#!/bin/sh
# Regenerates monolith/src/Layers/xrRenderVK/vk_pending.gen.cpp from what xray_vk still lacks:
# empties it, links, collects the undefined references, generates "not implemented" definitions,
# links again. Prints the number of methods still pending. Also handles plain C entry points.
set -e
cd "$(dirname "$0")/.."
P=monolith/src/Layers/xrRenderVK/vk_pending.gen.cpp
printf '// GENERATED by tools/vk_pending.sh - emptied for a link probe.\n' > $P
LC_ALL=C ninja -C build/monolith xray_vk > build/vk_link_probe.log 2>&1 || true
if grep " error:" build/vk_link_probe.log | grep -qv "linker command failed"; then grep " error:" build/vk_link_probe.log | head; exit 1; fi
grep -oE "undefined reference to \`[^']+'" build/vk_link_probe.log | sed -E "s/undefined reference to .//; s/'$//" | sort -u > build/vk_undefined.txt
python3 tools/gen_vk_pending.py build/vk_undefined.txt
LC_ALL=C ninja -C build/monolith xray_vk > build/vk_link.log 2>&1 || { grep -E "error|undefined" build/vk_link.log | head -20; exit 1; }
echo "xray_vk linked; pending: $(grep -c 'xrvk::not_implemented' $P)"
