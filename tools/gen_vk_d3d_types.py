#!/usr/bin/env python3
"""Generates monolith/src/Layers/xrRenderVK/vk_d3d_types.gen.h: the plain D3D11/DXGI data types
(enums, POD structs, #define constants) the shared render layer uses, extracted with their
dependencies from the WIDL-generated headers shipped with dxvk-native (Wine/mingw-w64 IDL, LGPL-2.1).
Only data definitions are copied - no COM interfaces, no functions. Usage: gen_vk_d3d_types.py
Names come from (a) the POD typedefs of xrRenderDX10/DXCommonTypes.h and (b) every D3D11_/D3D10_/
D3D_/DXGI_ identifier in the sources the xrRender_VK target compiles.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, 'build/deps/dxvk-native-3.1.1/usr/include/dxvk')
HEADERS = ['dxgiformat.h', 'dxgitype.h', 'dxgicommon.h', 'd3dcommon.h', 'd3d11.h', 'd3d11shader.h']
OUT = os.path.join(ROOT, 'monolith/src/Layers/xrRenderVK/vk_d3d_types.gen.h')

text = {h: open(os.path.join(INC, h), encoding='latin-1').read() for h in HEADERS if os.path.exists(os.path.join(INC, h))}

# definition tables: name -> (header, code)
defs, value_owner, order = {}, {}, []
for h, t in text.items():
    for m in re.finditer(r'typedef (enum|struct) (\w+)\s*\{(.*?)\}\s*(\w+)\s*;', t, re.S):
        kind, tag, body, name = m.groups()
        defs[name] = (h, m.group(0)); order.append(name)
        if tag != name:
            defs.setdefault(tag, defs[name])
        if kind == 'enum':
            for v in re.findall(r'^\s*(\w+)\s*(?:=|,|$)', body, re.M):
                value_owner[v] = name
    for m in re.finditer(r'^#define (\w+)\s+(\(?[-\w.\s|()<>x]+\)?)\s*$', t, re.M):
        name = m.group(1)
        if name.startswith(('D3D', 'DXGI')) and not name.endswith('_H') and '__' not in name:
            defs.setdefault(name, (h, m.group(0)))
            if name not in order:
                order.append(name)
    for m in re.finditer(r'^typedef (\w+) (\w+);', t, re.M):  # simple aliases, e.g. D3D11_RECT
        if m.group(2).startswith(('D3D', 'DXGI')):
            defs.setdefault(m.group(2), (h, m.group(0))); order.append(m.group(2))

def wanted_names():
    names = set()
    dxc = open(os.path.join(ROOT, 'monolith/src/Layers/xrRenderDX10/DXCommonTypes.h'), encoding='latin-1').read()
    names |= set(re.findall(r'\b(D3D11_\w+|D3D10_\w+|D3D_\w+|DXGI_\w+)\b', dxc))
    cmds = json.load(open(os.path.join(ROOT, 'build/monolith/compile_commands.json')))
    files = {c['file'] for c in cmds if 'xrRender_VK.dir' in c['command']}
    layers = os.path.join(ROOT, 'monolith/src/Layers')
    for d in ('xrRender', 'xrRenderPC_R4'):
        for dp, _, fs in os.walk(os.path.join(layers, d)):
            files |= {os.path.join(dp, f) for f in fs if f.endswith('.h')}
    for f in files:
        if '/xrRenderDX10/' in f and 'dx10' in os.path.basename(f):
            continue
        try:
            names |= set(re.findall(r'\b(D3D11_\w+|D3D10_\w+|D3D_\w+|DXGI_\w+)\b', open(f, encoding='latin-1').read()))
        except OSError:
            pass
    return names

def resolve(names):
    out, seen = [], set()
    def add(n):
        n = value_owner.get(n, n)
        if n in seen or n not in defs:
            return
        seen.add(n)
        code = defs[n][1]
        for dep in re.findall(r'\b(D3D\w+|DXGI\w+)\b', code):
            if dep != n:
                add(dep)
        out.append(n)
    for n in sorted(names):
        add(n)
        # D3D_x aliases used by the layer map to D3D11_x
        if n.startswith('D3D_') and not n.startswith('D3D_FEATURE'):
            add('D3D11_' + n[4:])
    return out

names = wanted_names()
res = resolve(names)
missing = sorted(n for n in names if value_owner.get(n, n) not in defs and not n.startswith(('D3D_', 'D3D10_')))
seen_code, lines = set(), []
for n in res:
    code = defs[n][1]
    if code in seen_code:
        continue
    seen_code.add(code)
    lines.append(code)
hdr = ['// GENERATED by tools/gen_vk_d3d_types.py - do not edit.',
       '// Plain D3D11/DXGI data types (enums, POD structs, constants) used by the shared render layer,',
       '// extracted from the WIDL-generated headers of Wine/mingw-w64 (LGPL-2.1) shipped with dxvk-native.',
       '// No interfaces or functions. Needs the Win32 base types (UINT, BOOL, FLOAT, ...).',
       '#pragma once', '']
open(OUT, 'w').write('\n'.join(hdr + lines) + '\n')
print(f'{len(names)} names used, {len(lines)} definitions written to {os.path.relpath(OUT, ROOT)}')
if missing:
    print('not found (interfaces/macros to provide by hand):', ' '.join(missing[:80]))
