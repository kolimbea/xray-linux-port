#!/usr/bin/env python3
"""Generates monolith/src/Layers/xrRenderVK/vk_d3d_types.gen.h: every plain data definition (enums,
structs, unions, typedefs, #define constants, IID GUIDs) of the D3D11/DXGI headers the renderer uses,
in header order, for the Vulkan backend (ADR 0001).

Source: the WIDL-generated headers of Wine/mingw-w64 (LGPL-2.1) shipped with dxvk-native. Removed:
interface definitions (__X_INTERFACE_DEFINED__ blocks; the backend's own classes are generated by
gen_vk_d3d_interfaces.py), interface forward declarations, #include lines, function prototypes and the
CD3D11_* helper classes. Interfaces are forward-declared at the top so structs can hold pointers.
Usage: gen_vk_d3d_interfaces.py && gen_vk_d3d_types.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, 'build/deps/dxvk-native-3.1.1/usr/include/dxvk')
HEADERS = ['dxgiformat.h', 'dxgicommon.h', 'dxgitype.h', 'd3dcommon.h', 'dxgi.h', 'dxgi1_2.h', 'dxgi1_3.h',
           'dxgi1_4.h', 'dxgi1_5.h', 'dxgi1_6.h', 'd3d11.h', 'd3d11_1.h', 'd3d11_2.h', 'd3d11shader.h']
OUT = os.path.join(ROOT, 'monolith/src/Layers/xrRenderVK/vk_d3d_types.gen.h')

def strip(t):
    # interface definitions and forward declarations
    t = re.sub(r'#ifndef __(\w+)_INTERFACE_DEFINED__\n.*?#endif\s*/\*\s*__\1_INTERFACE_DEFINED__\s*\*/\n', '', t, flags=re.S)
    t = re.sub(r'#ifndef __(\w+)_FWD_DEFINED__\n.*?#endif\n', '', t, flags=re.S)
    # d3d11shader.h style interfaces
    t = re.sub(r'#define INTERFACE \w+\nDECLARE_INTERFACE_?\([^)]*\)\s*\{.*?\n\};\n(#undef INTERFACE\n)?', '', t, flags=re.S)
    t = re.sub(r'^#include .*\n', '', t, flags=re.M)
    # free function prototypes (may span lines)
    t = re.sub(r'^(?:HRESULT|void|UINT|BOOL)\s+(?:WINAPI|__stdcall)\s+\w+\s*\([^;]*?\);\n', '', t, flags=re.M | re.S)
    t = re.sub(r'^typedef HRESULT \(WINAPI \*PFN_\w+\)\([^;]*?\);\n', '', t, flags=re.M | re.S)
    # interface typedef helpers
    t = re.sub(r'^typedef (?:interface )?(?:ID3D|IDXGI)\w+ \*?(?:LP)?\w+;\n', '', t, flags=re.M)
    return t

forwards = set()
parts = ['// GENERATED by tools/gen_vk_d3d_types.py - do not edit. See the script for provenance.',
         '#pragma once', '#define D3D11_NO_HELPERS', '']
bodies = []
for h in HEADERS:
    p = os.path.join(INC, h)
    if not os.path.exists(p):
        continue
    t = open(p, encoding='latin-1').read()
    forwards |= set(re.findall(r'#ifndef __((?:ID3D|IDXGI)\w+)_FWD_DEFINED__', t))
    forwards |= set(re.findall(r'DECLARE_INTERFACE_?\(((?:ID3D|IDXGI)\w+)', t))
    bodies.append('// ---- from %s ----\n' % h + strip(t))
parts += ['struct %s;' % f for f in sorted(forwards)] + [''] + bodies
open(OUT, 'w').write('\n'.join(parts) + '\n')
print(len(forwards), 'interfaces forward-declared;', sum(b.count('\n') for b in bodies), 'lines ->', os.path.relpath(OUT, ROOT))
