#!/usr/bin/env python3
"""Generates monolith/src/Layers/xrRenderVK/vk_d3d_interfaces.gen.h: classes named like the D3D11/DXGI
interfaces the renderer uses, with the same method signatures, for the Vulkan backend (ADR 0001).

Taken from the C++ sections of the WIDL-generated headers (Wine/mingw-w64, LGPL-2.1) shipped with
dxvk-native - declarations only. Differences from COM: methods are ordinary non-virtual members,
implemented in Layers/xrRenderVK/*.cpp (a method that is declared but not implemented fails at link
time, so nothing is silently stubbed); IUnknown is xrRenderVK's own reference-counted base with a
virtual destructor (xrvk::ComBase in vkCommonTypes.h). ID3DInclude keeps its virtual methods because the engine implements it.
Each class may get backend members through a macro XRVK_EXTRA_<Interface> (see vkMembers.h).
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, 'build/deps/dxvk-native-3.1.1/usr/include/dxvk')
HEADERS = ['d3dcommon.h', 'dxgi.h', 'dxgi1_2.h', 'dxgi1_3.h', 'dxgi1_4.h', 'd3d11.h', 'd3d11_1.h', 'd3d11_2.h', 'd3d11shader.h']
OUT = os.path.join(ROOT, 'monolith/src/Layers/xrRenderVK/vk_d3d_interfaces.gen.h')
KEEP_VIRTUAL = {'ID3DInclude'}

ifaces = {}  # name -> dict(base, uuid, methods[list of (ret, name, args)])
order = []

def clean_args(a):
    a = re.sub(r'\s+', ' ', a.strip())
    return a

for h in HEADERS:
    t = open(os.path.join(INC, h), encoding='latin-1').read()
    # MIDL C++ blocks
    for m in re.finditer(r'(?:MIDL_INTERFACE\("([0-9a-fA-F-]+)"\)\s*\n)?(?:interface )?(\w+)(?: : public (\w+))?\s*\n\{\n(.*?)\n\};', t, re.S):
        uuid, name, base, body = m.groups()
        if not re.match(r'^(ID3D|IDXGI)', name) or name in ifaces:
            continue
        meths = [(r.strip(), n, clean_args(a)) for r, n, a in
                 re.findall(r'virtual\s+(.+?)\s+STDMETHODCALLTYPE\s+(\w+)\s*\((.*?)\)\s*(?:const\s*)?=\s*0\s*;', body, re.S)]
        ifaces[name] = dict(base=base, uuid=uuid, methods=meths); order.append(name)
    # DECLARE_INTERFACE blocks (d3d11shader.h)
    for m in re.finditer(r'DECLARE_INTERFACE_?\((\w+)(?:\s*,\s*(\w+))?\)\s*\{(.*?)\n\};', t, re.S):
        name, base, body = m.groups()
        if name in ifaces:
            continue
        meths = []
        for kind, a, rest in re.findall(r'STDMETHOD(_?)\(([^)]*)\)\s*\(THIS_?\s*(.*?)\)\s*PURE\s*;', body, re.S):
            if kind:
                ret, n = [x.strip() for x in a.rsplit(',', 1)]
            else:
                ret, n = 'HRESULT', a.strip()
            meths.append((ret, n, clean_args(rest)))
        ifaces[name] = dict(base=base, uuid=None, methods=meths); order.append(name)

for n, i in ifaces.items():  # DECLARE_INTERFACE uuids come from DEFINE_GUID(IID_<name>, ...)
    if not i['uuid']:
        for h in HEADERS:
            g = re.search(r'DEFINE_GUID\(IID_%s,\s*([^)]*)\)' % n, open(os.path.join(INC, h), encoding='latin-1').read())
            if g:
                i['guid_args'] = g.group(1)

UNKNOWN = {'QueryInterface', 'AddRef', 'Release'}
def emit(name, out, done):
    if name in done or name not in ifaces:
        return
    i = ifaces[name]
    if i['base'] and i['base'] != 'IUnknown':
        emit(i['base'], out, done)
    done.add(name)
    b = 'xrvk::ComBase' if i['base'] == 'IUnknown' else i['base']  # concrete ref-counted root
    base = (' : public ' + b) if b else ''
    out.append('struct %s%s\n{' % (name, base))
    virt = name in KEEP_VIRTUAL
    if virt:
        out.append('    virtual ~%s() = default;' % name)
    for ret, mname, args in i['methods']:
        if mname in UNKNOWN and i['base'] is not None:
            continue
        if mname in UNKNOWN:  # a root interface (shader reflection children have no IUnknown)
            continue
        out.append('    %s%s %s(%s)%s;' % ('virtual ' if virt else '', ret, mname, args, ' = 0' if virt else ''))
    out.append('#ifdef XRVK_EXTRA_%s\n    XRVK_EXTRA_%s\n#endif' % (name, name))
    out.append('};')

out = ['// GENERATED by tools/gen_vk_d3d_interfaces.py - do not edit. See the script for what this is.',
       '#pragma once', '']
out += ['struct %s;' % n for n in order]
out.append('')
done = set()
for n in order:
    emit(n, out, done)
out.append('')
ALREADY = {'ID3D11ShaderReflection'}  # MonolithCompat.inl declares its __uuidof mapping engine-wide
for n in order:
    i = ifaces[n]
    if n in ALREADY:
        continue
    if i.get('uuid'):
        u = i['uuid'].replace('-', '')
        parts = [u[0:8], u[8:12], u[12:16]] + [u[16 + 2 * k:18 + 2 * k] for k in range(8)]
        out.append('DECLARE_UUIDOF_HELPER(%s, 0x%s)' % (n, ', 0x'.join(parts)))
    elif i.get('guid_args'):
        out.append('DECLARE_UUIDOF_HELPER(%s, %s)' % (n, i['guid_args']))
open(OUT, 'w').write('\n'.join(out) + '\n')
print(len(order), 'interfaces,', sum(len(i['methods']) for i in ifaces.values()), 'methods ->', os.path.relpath(OUT, ROOT))
