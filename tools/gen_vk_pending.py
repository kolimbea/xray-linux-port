#!/usr/bin/env python3
"""Writes monolith/src/Layers/xrRenderVK/vk_pending.gen.cpp: a definition for every D3D11-named method
the renderer calls that the Vulkan backend does not implement yet. Each one stops the game with
"vk: <Class::Method> not implemented" (xrvk::not_implemented), so nothing runs on a silent stub.
Input: the linker's undefined references of xray_vk (one mangled name per line, see PROGRESS.md).
Usage: gen_vk_pending.py <undefined-symbols.txt>. Re-run after implementing methods to shrink the file.
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = os.path.join(ROOT, 'monolith/src/Layers/xrRenderVK/vk_d3d_interfaces.gen.h')
OUT = os.path.join(ROOT, 'monolith/src/Layers/xrRenderVK/vk_pending.gen.cpp')

mangled = [l.strip() for l in open(sys.argv[1]) if l.strip()]
demangled = subprocess.run(['c++filt'], input='\n'.join(mangled), capture_output=True, text=True).stdout.splitlines()
wanted = {}
for d in demangled:
    m = re.match(r'^(\w+)::(\w+)\((.*)\)$', d)
    if m and m.group(1).startswith(('ID3D', 'IDXGI')):
        wanted.setdefault((m.group(1), m.group(2)), []).append(m.group(3))

decls, cls = {}, None
for line in open(HDR):
    m = re.match(r'^struct (\w+)', line)
    if m:
        cls = m.group(1)
        continue
    m = re.match(r'^    (.+?)\s+(\w+)\((.*)\);$', line)
    if cls and m:
        decls.setdefault((cls, m.group(2)), []).append((m.group(1), m.group(3)))

out = ['// GENERATED by tools/gen_vk_pending.py - do not edit. Methods the Vulkan backend has not implemented',
       '// yet; each stops the game with a clear message. Implemented methods disappear from this file.',
       '#include "stdafx.h"', '#include "vkBase.h"', '']
missing = []
for (c, mth), _ in sorted(wanted.items()):
    if (c, mth) not in decls:
        missing.append(c + '::' + mth)
        continue
    for ret, args in decls[(c, mth)]:
        out.append('%s %s::%s(%s)\n{\n    xrvk::not_implemented("%s::%s");\n}\n' % (ret, c, mth, args, c, mth))
open(OUT, 'w').write('\n'.join(out))
print(len(wanted), 'methods ->', os.path.relpath(OUT, ROOT))
if missing:
    print('not in the generated interfaces:', ' '.join(missing))
